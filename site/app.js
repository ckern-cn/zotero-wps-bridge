(function () {
    'use strict';

    const config = window.ZW_SITE || {};
    const $ = (selector, root) => (root || document).querySelector(selector);
    const $$ = (selector, root) => Array.prototype.slice.call(
        (root || document).querySelectorAll(selector));

    function applyLink(element, href) {
        if (!href) {
            return;
        }
        element.setAttribute('href', href);
        if (/^https?:\/\//i.test(href)
                && element.getAttribute('target') === '_blank') {
            element.setAttribute('rel', 'noopener');
        }
    }

    /* Static links that are centralised in config.js. */
    const linkKeys = [
        'repo', 'gitee', 'github', 'releases', 'issues', 'changelog',
        'license', 'security', 'donate', 'updates'
    ];
    for (const key of linkKeys) {
        for (const element of $$('[data-link="' + key + '"]')) {
            applyLink(element, config[key]);
        }
    }

    const downloadKeys = ['xpi', 'zip', 'checksums'];
    for (const key of downloadKeys) {
        for (const element of $$('[data-download="' + key + '"]')) {
            applyLink(element, config[key]);
        }
    }

    /* version.json is generated by scripts/build-site.js. It keeps download
     * links and the version badge in sync without editing the HTML by hand. */
    fetch('/version.json', { cache: 'no-store' })
        .then(function (response) {
            if (!response.ok) {
                throw new Error('version.json ' + response.status);
            }
            return response.json();
        })
        .then(function (version) {
            if (version.version) {
                for (const element of $$('[data-version]')) {
                    element.textContent = 'v' + version.version;
                }
            }
            if (version.date) {
                for (const element of $$('[data-release-date]')) {
                    element.textContent = version.date;
                }
            }
            const downloads = {
                xpi: version.xpi || config.xpi,
                zip: version.zip || config.zip,
                checksums: version.checksums || config.checksums
            };
            for (const key of Object.keys(downloads)) {
                for (const element of $$('[data-download="' + key + '"]')) {
                    applyLink(element, downloads[key]);
                }
            }
        })
        .catch(function () {
            /* The site remains usable with the static fallback links. */
        });

    /* Header state and back-to-top visibility */
    const header = $('.site-header');
    const backToTop = $('[data-back-to-top]');
    function updateScrollUI() {
        if (header) {
            header.classList.toggle('scrolled', window.scrollY > 8);
        }
        if (backToTop) {
            backToTop.classList.toggle('is-visible', window.scrollY > 560);
        }
    }
    window.addEventListener('scroll', updateScrollUI, { passive: true });
    updateScrollUI();

    /* Mobile navigation */
    const navToggle = $('.nav-toggle');
    const nav = $('#site-nav');
    function closeNav() {
        document.body.classList.remove('nav-open');
        if (navToggle) {
            navToggle.setAttribute('aria-expanded', 'false');
        }
    }

    /* Back to top: the sticky header itself cannot be used as an anchor
     * target, so both the logo and the floating button scroll the window. */
    const reduceMotion = window.matchMedia
        ? window.matchMedia('(prefers-reduced-motion: reduce)')
        : { matches: false };
    function scrollToTop() {
        window.scrollTo({
            top: 0,
            behavior: reduceMotion.matches ? 'auto' : 'smooth'
        });
    }
    for (const link of $$('a[href="#top"]')) {
        link.addEventListener('click', function (event) {
            event.preventDefault();
            closeNav();
            scrollToTop();
        });
    }
    if (backToTop) {
        backToTop.addEventListener('click', scrollToTop);
    }
    if (navToggle && nav) {
        navToggle.addEventListener('click', function () {
            const open = !document.body.classList.contains('nav-open');
            document.body.classList.toggle('nav-open', open);
            navToggle.setAttribute('aria-expanded', open ? 'true' : 'false');
        });
        for (const link of $$('a', nav)) {
            link.addEventListener('click', closeNav);
        }
        window.addEventListener('keydown', function (event) {
            if (event.key === 'Escape') {
                closeNav();
            }
        });
        window.addEventListener('resize', function () {
            if (window.innerWidth > 760) {
                closeNav();
            }
        });
    }

    /* Section indicator for the single-page navigation */
    const sectionLinks = $$('.site-nav > a[href^="#"]')
        .map(function (link) {
            const id = link.getAttribute('href').slice(1);
            const section = id ? document.getElementById(id) : null;
            return section ? { link: link, section: section } : null;
        })
        .filter(Boolean);

    let navFrame = 0;
    function updateActiveSection() {
        navFrame = 0;
        if (!sectionLinks.length) {
            return;
        }
        const offset = (header ? header.offsetHeight : 0) + 96;
        let active = null;
        for (const item of sectionLinks) {
            if (item.section.getBoundingClientRect().top <= offset) {
                active = item;
            }
        }
        if (window.innerHeight + window.scrollY >=
                document.documentElement.scrollHeight - 2) {
            active = sectionLinks[sectionLinks.length - 1];
        }
        for (const item of sectionLinks) {
            const current = item === active;
            item.link.classList.toggle('is-active', current);
            if (current) {
                item.link.setAttribute('aria-current', 'location');
            }
            else {
                item.link.removeAttribute('aria-current');
            }
        }
    }
    function requestActiveSection() {
        if (navFrame) {
            return;
        }
        navFrame = window.requestAnimationFrame(updateActiveSection);
    }
    window.addEventListener('scroll', requestActiveSection, { passive: true });
    window.addEventListener('resize', requestActiveSection);
    updateActiveSection();

    /* Reveal on scroll */
    const revealItems = $$('[data-reveal]');
    if (revealItems.length) {
        if (!('IntersectionObserver' in window)) {
            for (const item of revealItems) {
                item.classList.add('is-visible');
            }
        }
        else {
            const observer = new IntersectionObserver(function (entries) {
                for (const entry of entries) {
                    if (!entry.isIntersecting) {
                        continue;
                    }
                    const delay = Number(entry.target.getAttribute('data-reveal-delay'));
                    if (delay > 0) {
                        entry.target.style.setProperty('--reveal-delay', delay + 'ms');
                    }
                    entry.target.classList.add('is-visible');
                    observer.unobserve(entry.target);
                }
            }, {
                rootMargin: '0px 0px -48px 0px',
                threshold: 0.08
            });
            for (const item of revealItems) {
                observer.observe(item);
            }
        }
    }

    /* Footer year */
    for (const element of $$('[data-year]')) {
        element.textContent = String(new Date().getFullYear());
    }
})();
